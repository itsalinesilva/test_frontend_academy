/**
 * Livreto de exercícios — História da Música Brasileira.
 *
 * Três questões por capítulo. Várias delas cobram a **leitura crítica** que o
 * curso faz: por que a fórmula das três raças descreve mal o processo, por que
 * exigir folclore de Carlos Gomes é anacronismo, por que "regional" funciona
 * como rebaixamento.
 *
 * Não são questões de opinião: cada uma tem uma resposta que o capítulo
 * sustenta com argumento. O que se mede é se o aluno acompanhou o argumento.
 */

function q(
  id: string,
  prompt: string,
  choices: string[],
  correta: number,
  explanation: string,
  competencias: string[],
  dificuldade: DificuldadeQuestao = 'basica'
): Questao {
  const letras = ['a', 'b', 'c', 'd'];
  return {
    id,
    prompt,
    tipo: 'MULTIPLA_ESCOLHA',
    choices: choices.map((texto, i) => ({ id: letras[i], texto })),
    resposta: letras[correta],
    explanation,
    dificuldade,
    competencias,
  };
}

