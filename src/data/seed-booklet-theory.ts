import { Livreto, Questao, CapituloLivreto, DificuldadeQuestao } from '../domain/booklet';

/**
 * Livreto de exercícios — Teoria da Música, Fundamentos.
 *
 * SEIS A OITO QUESTÕES POR CAPÍTULO — a quantidade sai da síntese.
 * -------------------------------------------
 * É o número que cabe numa sessão de fixação sem virar prova. Menos que
 * quatro não cobre o capítulo; mais que oito e o aluno para de responder
 * pensando e passa a responder para terminar — e aí a fixação não fixa nada.
 *
 * A mesma quantidade em todos os capítulos é deliberada: a validação do
 * livreto acusa desequilíbrio, e um capítulo com o triplo do outro faz o
 * curso parecer perder o fôlego no meio.
 *
 * TODA QUESTÃO TEM EXPLICAÇÃO.
 * ----------------------------
 * Não é formalidade: uma questão sem explicação ensina a acertar, não o
 * assunto. A explicação é onde a questão vira aula — é o que o aluno lê
 * depois de errar, e é a única parte que ele lê com atenção total.
 *
 * As alternativas erradas também não são aleatórias. Cada uma corresponde a
 * um engano real e frequente: confundir altura com intensidade, ler 6/8 como
 * seis tempos, contar intervalo sem incluir as pontas.
 */

function q(
  id: string,
  enunciado: string,
  alternativas: string[],
  correta: number,
  explicacao: string,
  competencias: string[],
  dificuldade: DificuldadeQuestao = 'basica'
): Questao {
  const letras = ['a', 'b', 'c', 'd'];
  return {
    id,
    enunciado,
    tipo: 'MULTIPLA_ESCOLHA',
    alternativas: alternativas.map((texto, i) => ({ id: letras[i], texto })),
    resposta: letras[correta],
    explicacao,
    dificuldade,
    competencias,
  };
}

