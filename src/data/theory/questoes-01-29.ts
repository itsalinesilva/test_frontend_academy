import { Questao, DificuldadeQuestao } from '../../domain/booklet';

export function q(
  id: string,
  prompt: string,
  choices: string[],
  correta: number,
  explanation: string,
  competencias: string[],
  dificuldade: DificuldadeQuestao = 'basica'
): Questao {
  const letras = ['a', 'b', 'c', 'd'];
  return {
    id,
    prompt,
    tipo: 'MULTIPLA_ESCOLHA',
    choices: choices.map((texto, i) => ({ id: letras[i], texto })),
    resposta: letras[correta],
    explanation,
    dificuldade,
    competencias,
  };
}

