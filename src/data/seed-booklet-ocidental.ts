/**
 * Livreto de exercícios — História da Música Ocidental.
 *
 * Três questões por capítulo. História não se fixa por repetição mecânica: a
 * questão útil aqui é a que pede **relação** — por que tal coisa levou a tal
 * outra —, e não a que pergunta a data.
 *
 * Nenhuma questão cobra ano de nascimento nem nome de obra. O que o curso
 * ensina é a sucessão de problemas técnicos, e é isso que as questões medem.
 */

function q(
  id: string,
  prompt: string,
  choices: string[],
  correta: number,
  explanation: string,
  competencias: string[],
  dificuldade: DificuldadeQuestao = 'basica'
): Questao {
  const letras = ['a', 'b', 'c', 'd'];
  return {
    id,
    prompt,
    tipo: 'MULTIPLA_ESCOLHA',
    choices: choices.map((texto, i) => ({ id: letras[i], texto })),
    resposta: letras[correta],
    explanation,
    dificuldade,
    competencias,
  };
}

