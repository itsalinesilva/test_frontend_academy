/**
 * Livreto de exercícios — Violino.
 *
 * Três questões por capítulo. Num curso de instrumento, a questão escrita não
 * substitui a prática — ela verifica se o aluno **entendeu a causa** do que
 * faz com as mãos.
 *
 * Por isso quase toda questão aqui é de diagnóstico: dado um defeito de som
 * ou de execução, qual é a causa. É o que permite estudar sozinho, que é o
 * objetivo declarado do capítulo final.
 */

function q(
  id: string,
  enunciado: string,
  alternativas: string[],
  correta: number,
  explicacao: string,
  competencias: string[],
  dificuldade: DificuldadeQuestao = 'basica'
): Questao {
  const letras = ['a', 'b', 'c', 'd'];
  return {
    id,
    enunciado,
    tipo: 'MULTIPLA_ESCOLHA',
    alternativas: alternativas.map((texto, i) => ({ id: letras[i], texto })),
    resposta: letras[correta],
    explicacao,
    dificuldade,
    competencias,
  };
}

